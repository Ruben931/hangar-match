let currentLang = "en";

export function detectLang() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved && TRANSLATIONS[saved]) return saved;
  const navLangs = navigator.languages || [navigator.language || "en"];
  for (const l of navLangs) {
    const code = String(l).slice(0, 2).toLowerCase();
    if (TRANSLATIONS[code]) return code;
  }
  return "en";
}

export function getLang() {
  return currentLang;
}

export function setLang(code) {
  if (!TRANSLATIONS[code]) code = "en";
  currentLang = code;
  localStorage.setItem(STORAGE_KEY, code);
}

export function initLang() {
  currentLang = detectLang();
  return currentLang;
}

export function localeOf() {
  return LOCALES[currentLang] || "en-US";
}

/** t("key") ou t("roles.cargo"), avec variables {n}, {s}, … */
export function t(key, vars) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  const fallback = TRANSLATIONS.en;
  let value = key.split(".").reduce((o, k) => (o ? o[k] : undefined), dict);
  if (value === undefined) {
    value = key.split(".").reduce((o, k) => (o ? o[k] : undefined), fallback);
  }
  if (value === undefined) return key;
  if (typeof value === "string" && vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replaceAll(`{${k}}`, v);
    }
  }
  return value;
}
